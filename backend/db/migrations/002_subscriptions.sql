-- Модель подписок: период действия текущего плана.
--
-- Текущий план пользователя уже хранится в существующей колонке users.subscription_type
-- (значения: 'free' / 'pro'). Новое поле фиксирует, до какого момента действует план.
-- NULL = срок не ограничен (например, бесплатный тариф).
--
-- Совместимость с существующими пользователями: ADD COLUMN IF NOT EXISTS добавляет
-- колонку только если её ещё нет, а NULL по умолчанию не меняет существующие строки.

ALTER TABLE users
    ADD COLUMN IF NOT EXISTS subscription_expires_at TIMESTAMPTZ;
