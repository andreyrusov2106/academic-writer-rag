-- Миграция: увеличение лимита бесплатных запросов Free с 10 до 100.
--
-- Контекст: PLANS["free"]["requests_limit"] в коде уже равен 100, и новые
-- пользователи получают 100 при регистрации (create_user_in_db пишет текущее
-- значение PLANS в users.requests_limit). Но у уже существующих free-пользователей
-- в users.requests_limit осталось старое значение 10, записанное при регистрации,
-- когда лимит был 10. Рантайм-проверка try_reserve_request() сравнивает
-- requests_used < users.requests_limit, поэтому такие пользователи блокируются
-- на 10 запросах, несмотря на новый лимит 100 в коде.
--
-- Это точечный data-fix: обновляем ТОЛЬКО free-пользователей со старым лимитом 10.
-- Пользователи с любым другим requests_limit (например, кастомным или pro) не
-- затрагиваются, чтобы не перезаписать их индивидуальные значения.

UPDATE users
SET requests_limit = 100
WHERE subscription_type = 'free'
  AND requests_limit = 10;
